export function publicImageUrl(value) {
  if(!value || typeof window === 'undefined' || window.location.protocol !== 'https:') return value || '';
  try {
    const url=new URL(value);
    const prefix='/storage/v1/object/public/player-photos/';
    if(url.hostname.endsWith('.supabase.co') && url.pathname.startsWith(prefix)) return '/api/club-image?path='+encodeURIComponent(decodeURIComponent(url.pathname.slice(prefix.length)));
  } catch { /* Relative site assets and data/blob previews stay unchanged. */ }
  return value;
}
export function playerCard(player = {}) {
  if(player.cardImageRemoved) return '';
  const bundled=cards[player.name];
  // This exact uploaded edition is already bundled with the deployed website.
  // Later administrator replacements keep their own storage URL and image data.
  if(bundled && player.cardImage?.includes('/cards/jiangte-refresh-20261029/') && player.cardImage.split('/').pop()===bundled.split('/').pop()) return bundled;
  return publicImageUrl(player.cardImage || bundled || '');
}
// Linked player records and their team match describe the same event, not extra appearances.
export function uniquePlayerRecords(records = []) {
  const map = new Map();
  for (const record of records) {
    const key = record.teamMatchId
      ? `id:${record.teamMatchId}`
      : `${record.date}|${record.opponent}`;
    const linked =
      record.teamMatchId &&
      [...map.entries()].find(
        ([, value]) =>
          !value.teamMatchId &&
          value.date === record.date &&
          value.opponent === record.opponent,
      );
    if (linked) map.delete(linked[0]);
    if (
      !record.teamMatchId &&
      [...map.values()].some(
        (value) =>
          value.teamMatchId &&
          value.date === record.date &&
          value.opponent === record.opponent,
      )
    )
      continue;
    if (!map.has(key) || !record.autoGenerated) map.set(key, record);
  }
  return [...map.values()];
}
export function validatePayload(payload) {
  if (
    !payload ||
    !Array.isArray(payload.players) ||
    !Array.isArray(payload.teamMatches)
  )
    throw new Error("球队数据格式不完整，已阻止覆盖。");
  for (const key of ["coaches", "tacticsPositions", "trainingSessions"])
    if (payload[key] !== undefined && !Array.isArray(payload[key]))
      throw new Error(`${key} 数据格式错误`);
  for (const key of ["clubInfo", "manualAwards", "nextMatch", "contentEdits"]) {
    if (
      payload[key] !== undefined &&
      (!payload[key] ||
        typeof payload[key] !== "object" ||
        Array.isArray(payload[key]))
    )
      throw new Error(`${key} 数据格式错误`);
  }
  if (
    payload.teamMatches.some(
      (match) => !match || typeof match !== "object" || Array.isArray(match),
    )
  )
    throw new Error("球队比赛数据格式错误");
  if (
    payload.players.some(
      (p) =>
        !p ||
        typeof p.name !== "string" ||
        (p.matches !== undefined && !Array.isArray(p.matches)),
    )
  )
    throw new Error("球员记录格式错误");
  return payload;
}
export function payloadSignature(payload) {
  const { savedAt, ...data } = payload;
  return JSON.stringify(data);
}

export const featuredNames = ["谭嘉铭", "章兮兮", "潘均毅", "黄非凡", "陆梓鑫"];
export function applyClubRefresh(payload) {
  if (payload.clubInfo?.rosterRefresh === "20261029-v2") return payload;
  const removed = new Set(["吴俊", "吴易玮"]);
  return {
    ...payload,
    players: payload.players
      .filter((p) => !removed.has(p.name))
      .map((p) => ({
        ...p,
        matches: [],
        clubRole: featuredNames.slice(0, 2).includes(p.name)
          ? "队长"
          : featuredNames.slice(2).includes(p.name)
            ? "领队"
            : p.clubRole || "",
        ...(cards[p.name]
          ? { cardImage: p.cardImage || cards[p.name], cardImageRemoved: false }
          : {}),
      })),
    coaches: (payload.coaches || []).map((c) => ({ ...c, matches: [] })),
    teamMatches: [],
    tacticsPositions: (payload.tacticsPositions || []).filter(
      (p) =>
        !removed.has(p.name) &&
        payload.players.some((player) => player.name === p.name),
    ),
    clubInfo: {
      ...payload.clubInfo,
      homeGround: "滨江热电",
      rosterRefresh: "20261029-v2",
    },
  };
}
export function externalUrl(value) {
  try {
    const url = new URL(String(value || "").trim());
    return ["https:", "http:"].includes(url.protocol) ? url.href : "";
  } catch {
    return "";
  }
}
