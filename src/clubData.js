// Linked player records and their team match describe the same event, not extra appearances.
export function uniquePlayerRecords(records = []) {
  const map = new Map();
  for (const record of records) {
    const key = record.teamMatchId
      ? `id:${record.teamMatchId}`
      : `${record.date}|${record.opponent}`;
    const linked =
      record.teamMatchId &&
      [...map.entries()].find(
        ([, value]) =>
          !value.teamMatchId &&
          value.date === record.date &&
          value.opponent === record.opponent,
      );
    if (linked) map.delete(linked[0]);
    if (
      !record.teamMatchId &&
      [...map.values()].some(
        (value) =>
          value.teamMatchId &&
          value.date === record.date &&
          value.opponent === record.opponent,
      )
    )
      continue;
    if (!map.has(key) || !record.autoGenerated) map.set(key, record);
  }
  return [...map.values()];
}
export function validatePayload(payload) {
  if (
    !payload ||
    !Array.isArray(payload.players) ||
    !Array.isArray(payload.teamMatches)
  )
    throw new Error("球队数据格式不完整，已阻止覆盖。");
  for (const key of ["coaches", "tacticsPositions", "trainingSessions"])
    if (payload[key] !== undefined && !Array.isArray(payload[key]))
      throw new Error(`${key} 数据格式错误`);
  for (const key of ["clubInfo", "manualAwards", "nextMatch", "contentEdits"]) {
    if (
      payload[key] !== undefined &&
      (!payload[key] ||
        typeof payload[key] !== "object" ||
        Array.isArray(payload[key]))
    )
      throw new Error(`${key} 数据格式错误`);
  }
  if (
    payload.teamMatches.some(
      (match) => !match || typeof match !== "object" || Array.isArray(match),
    )
  )
    throw new Error("球队比赛数据格式错误");
  if (
    payload.players.some(
      (p) =>
        !p ||
        typeof p.name !== "string" ||
        (p.matches !== undefined && !Array.isArray(p.matches)),
    )
  )
    throw new Error("球员记录格式错误");
  return payload;
}
export function payloadSignature(payload) {
  const { savedAt, ...data } = payload;
  return JSON.stringify(data);
}
